cssToAppend += ".flex-col-full { display: flex; flex-direction: column; height: 100%; min-height: 0; }\n";
['gate-open', 'gate-occupied', 'gate-unavail', 'sev-1', 'sev-2', 'sev-3', 'sev-4', 'sev-5', 'agent-disruption', 'status-landed', 'status-scheduled', 'status-in-air', 'status-at-gate', 'status-pushback', 'status-departed', 'status-cancelled'].forEach(k => {
  cssToAppend += `.bg-${k} { background: var(--${k}); }\n`;
});

